def print_separator(char="─", length=52, colour=C.GREY):
    print(clr(char * length, colour))

def get_highscores():
    if os.path.exists(HIGHSCORE_FILE):
        with open(HIGHSCORE_FILE, "r") as f:
            return json.load(f)
    return []

def save_highscore(name, score, total, category, difficulty, duration):
    scores = get_highscores()
    scores.append({
        "name": name,
        "score": score,
        "total": total,
        "pct": round((score/total)*100, 1),
        "category": category,
        "difficulty": difficulty,
        "duration": round(duration, 1),
        "date": datetime.now().strftime("%d %b %Y %H:%M")
    })
    scores.sort(key=lambda x: x["pct"], reverse=True)
    scores = scores[:10]  # keep top 10
    with open(HIGHSCORE_FILE, "w") as f:
        json.dump(scores, f, indent=2)

def show_highscores():
    scores = get_highscores()
    print_banner()
    print(clr("  🏆  TOP 10 HIGHSCORES", C.YELLOW + C.BOLD))
    print_separator()
    if not scores:
        print(clr("  No scores yet! Play a game first.", C.GREY))
    else:
        print(f"  {'#':<3} {'Name':<14} {'Score':<8} {'%':<7} {'Category':<18} {'Date'}")
        print_separator(char="·")
        for i, s in enumerate(scores, 1):
            medal = ["🥇","🥈","🥉"][i-1] if i <= 3 else f" {i}."
            pct_colour = C.GREEN if s['pct'] >= 70 else C.YELLOW if s['pct'] >= 50 else C.RED
            print(f"  {medal:<4} {s['name']:<14} {s['score']}/{s['total']:<6} "
                  f"{clr(str(s['pct'])+'%', pct_colour):<18} {s['category']:<18} {s['date']}")
    print_separator()
    input(clr("\n  Press Enter to go back...", C.GREY))

def get_grade(pct):
    if pct >= 90: return "A+", "Outstanding! 🌟"
    if pct >= 75: return "A",  "Excellent! 🎉"
    if pct >= 60: return "B",  "Good job! 👍"
    if pct >= 45: return "C",  "Not bad! Keep practising. 📚"
    if pct >= 30: return "D",  "Needs improvement. 💪"
    return "F", "Keep studying, you'll get there! 🔄"

def timed_input(prompt, timeout=TIME_LIMIT):
    """Input with a countdown timer (best-effort — works on Unix fully, Windows partially)."""
    import threading
    result = [None]
    answered = [False]

    def get_input():
        try:
            result[0] = input(prompt)
        except:
            result[0] = ""
        answered[0] = True

    t = threading.Thread(target=get_input, daemon=True)
    t.start()

    start = time.time()
    while not answered[0]:
        elapsed = time.time() - start
        remaining = timeout - elapsed
        if remaining <= 0:
            print(clr(f"\n  ⏰  Time's up!", C.RED))
            return None, timeout
        time.sleep(0.1)

    return result[0], time.time() - start



def menu_choose(prompt, options):
    """Display a numbered menu and return chosen value."""
    print(f"\n  {clr(prompt, C.CYAN + C.BOLD)}\n")
    for i, (label, _) in enumerate(options, 1):
        print(f"    {clr(str(i)+'.', C.YELLOW)}  {label}")
    print()
    while True:
        choice = input(clr("  Enter number: ", C.WHITE)).strip()
        if choice.isdigit() and 1 <= int(choice) <= len(options):
            return options[int(choice)-1][1]
        print(clr("  ⚠  Invalid choice, try again.", C.RED))



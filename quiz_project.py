def build_question_set(category, difficulty, num_questions):
    """Collect questions based on settings."""
    bank = []

    cats = list(QUESTIONS.keys()) if category == "All" else [category]
    diffs = ["easy", "medium", "hard"] if difficulty == "mixed" else [difficulty]

    for cat in cats:
        for diff in diffs:
            if cat in QUESTIONS and diff in QUESTIONS[cat]:
                for q in QUESTIONS[cat][diff]:
                    bank.append({**q, "category": cat, "difficulty": diff})

    random.shuffle(bank)
    return bank[:num_questions]


def run_quiz(player_name, category, difficulty, num_questions):
    questions = build_question_set(category, difficulty, num_questions)

    if not questions:
        print(clr("\n  ⚠  Not enough questions for that combination. Try 'All' categories.", C.YELLOW))
        time.sleep(2)
        return

    score = 0
    total = len(questions)
    wrong_answers = []
    total_time = 0

    for i, q in enumerate(questions, 1):
        clear_screen()

        # ── Header ──
        progress = "█" * i + "░" * (total - i)
        print(clr(f"\n  [{progress}]  Q{i}/{total}  |  {q['category']}  |  {q['difficulty'].upper()}  |  ⏱ {TIME_LIMIT}s", C.GREY))
        print_separator(colour=C.BLUE)

        # ── Question ──
        print(f"\n  {clr(f'Q{i}.', C.CYAN + C.BOLD)}  {clr(q['q'], C.WHITE + C.BOLD)}\n")
        for opt in q["options"]:
            print(f"      {clr(opt, C.TEXT if hasattr(C,'TEXT') else C.RESET)}")

        print()
        print_separator(char="·", colour=C.GREY)

        # ── Get Answer ──
        start = time.time()
        raw = input(clr(f"  Your answer (A/B/C/D) ⏱ [{TIME_LIMIT}s]: ", C.YELLOW)).strip().upper()
        elapsed = time.time() - start

        total_time += elapsed

        # ── Time check ──
        if elapsed > TIME_LIMIT:
            print(clr("\n  ⏰  Too slow! Moving on.", C.RED))
            wrong_answers.append({**q, "your_answer": "⏰ Timeout"})
            time.sleep(1.5)
            continue

        if raw not in ["A", "B", "C", "D"]:
            print(clr("  ⚠  Invalid input — skipping.", C.YELLOW))
            wrong_answers.append({**q, "your_answer": raw or "?"})
            time.sleep(1.2)
            continue

        # ── Evaluate ──
        correct = q["answer"]
        if raw == correct:
            score += 1
            print(clr(f"\n  ✅  CORRECT!  +1 point  ({elapsed:.1f}s)", C.GREEN + C.BOLD))
        else:
            print(clr(f"\n  ❌  WRONG!  Correct answer: {correct}", C.RED + C.BOLD))
            wrong_answers.append({**q, "your_answer": raw})

        print(clr(f"  💡  {q['explanation']}", C.GREY))
        time.sleep(2.2)

    # ── Results Screen ──
    clear_screen()
    pct = round((score / total) * 100, 1)
    grade, message = get_grade(pct)

    print(f"""
{C.CYAN}{C.BOLD}  ╔══════════════════════════════════════╗
  ║           QUIZ COMPLETE! 🎉           ║
  ╚══════════════════════════════════════╝{C.RESET}

  {clr('Player:', C.GREY)}   {clr(player_name, C.WHITE + C.BOLD)}
  {clr('Category:', C.GREY)} {category}  |  {clr('Difficulty:', C.GREY)} {difficulty.title()}
  {clr('Score:', C.GREY)}    {clr(f'{score} / {total}', C.CYAN + C.BOLD)}
  {clr('Accuracy:', C.GREY)} {clr(f'{pct}%', C.GREEN if pct >= 60 else C.RED)}
  {clr('Grade:', C.GREY)}    {clr(grade, C.YELLOW + C.BOLD)}
  {clr('Time:', C.GREY)}     {clr(f'{total_time:.1f}s total  ({(total_time/total):.1f}s avg/question)', C.GREY)}

  {clr(message, C.PURPLE + C.BOLD)}
    """)

    # Save score
    save_highscore(player_name, score, total, category, difficulty, total_time)

    # Show wrong answers
    if wrong_answers:
        print_separator()
        print(clr(f"\n  📝  Review — {len(wrong_answers)} wrong answer(s):\n", C.YELLOW))
        for j, w in enumerate(wrong_answers, 1):
            print(f"  {clr(str(j)+'.', C.GREY)} {w['q']}")
            print(f"     {clr('You answered:', C.RED)}  {w['your_answer']}   {clr('Correct:', C.GREEN)}  {w['answer']}")
            print(f"     {clr(w['explanation'], C.GREY)}\n")

    print_separator()
    input(clr("  Press Enter to return to menu...", C.GREY))


